/**
 * 将 `[/名称]` 替换为 Unicode 表情；未知名称替换为 `「名称」` 便于阅读。
 */
export function expandImBracketEmoticons(text: string): string {
  if (!text || !text.includes("[/")) return text;
  return text.replace(/\[\/([^\]]*)\]/g, (_full, name: string) => {
    const key = String(name).trim();
    if (!key) return _full;
    const emoji = BRACKET_EMOTICON_UNICODE[key];
    if (emoji) return emoji;
    return `「${key}」`;
  });
}
